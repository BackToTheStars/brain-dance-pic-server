// Таймауты исходящих операций. До этого у media их не было нигде: зависший
// внешний сервер держал наш запрос ровно столько, сколько его держал клиент.
// Значения разведены по природе операции — HTTP за чужим файлом и yt-dlp живут
// в разных масштабах времени.

// Проба размера через HEAD: в ответе только заголовки, ждать долго нечего.
const HTTP_HEAD_TIMEOUT = 10 * 1000;

// Скачивание файла по прямой ссылке. У axios это таймаут ПРОСТОЯ сокета
// (под капотом req.setTimeout), а не общая длительность запроса, поэтому
// большой, но живой файл его не задевает — сработает только на зависшем
// соединении.
const HTTP_DOWNLOAD_TIMEOUT = 60 * 1000;

// yt-dlp -J: сходить за метаданными, ничего не скачивая.
const YTDLP_PROBE_TIMEOUT = 60 * 1000;

// Скачивание через yt-dlp — общая длительность процесса (spawn timeout).
// Щедрый: это сотни мегабайт, а yt-dlp внутри ещё и ретраит фрагменты.
const YTDLP_DOWNLOAD_TIMEOUT = 30 * 60 * 1000;

module.exports = {
  HTTP_HEAD_TIMEOUT,
  HTTP_DOWNLOAD_TIMEOUT,
  YTDLP_PROBE_TIMEOUT,
  YTDLP_DOWNLOAD_TIMEOUT,
};
